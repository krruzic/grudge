def _scale_time(clips, w):
    if abs(w - 1.0) < 1e-6:
        return clips
    out = {}
    for name, clip in clips.items():
        if name in ("idle",):
            out[name] = clip
            continue
        c = {}
        for part in ("bones", "loc", "rot"):
            if part in clip:
                c[part] = {b: [(round(f * w), v) for f, v in keys] for b, keys in clip[part].items()}
        out[name] = c
    return out
