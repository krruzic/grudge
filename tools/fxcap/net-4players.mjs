await host.evaluate(() => { const s = grudge.slots[0]; s.ready = true; grudge.cursors.placeChip(0, s.hero); grudge.cursors.cursors[0].holding = -1; });
await host.waitForTimeout(600);
await tap(host, "Enter"); await host.waitForTimeout(800); await tap(host, "Enter");
