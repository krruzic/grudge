const hostRoom = info.rooms.find((r) => r.phase === "lobby").id;
const peers = [];
for (let i = 0; i < 3; i++) {
  const p = await mk("peer" + i);
  await tap(p, "KeyS");
  await tap(p, "Enter");
  await p.waitForFunction(() => grudge.menus.page === "browse" && grudge.menus.rooms.length >= 2, null, { timeout: 15000 });
  if (i === 0) await p.shot("browse");
  await p.evaluate((id) => { grudge.menus.focus = grudge.menus.rooms.findIndex((r) => r.id === id) + 1; }, hostRoom);
  await tap(p, "Enter");
  await p.waitForFunction(() => grudge.state === "lobby", null, { timeout: 15000 });
  peers.push(p);
}
await host.waitForTimeout(1500);
console.log("host slots", await host.evaluate(() => JSON.stringify(grudge.slots.map((s) => [s.hero, s.cpu, s.tag]))));
for (const p of peers) { await tap(p, "KeyE"); }
await host.waitForTimeout(1000);
