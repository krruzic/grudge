console.log("all 4 in match", JSON.stringify(await Promise.all(peers.map((p) => p.evaluate(() => grudge.net.mySlot)))));
const start = await host.evaluate(() => [1, 2, 3].map((i) => { const t = grudge.world.heroForPlayer(i).transform.pos; return [t.x.toFixed(1), t.z.toFixed(1)]; }));
for (const p of peers) await p.keyboard.down("KeyW");
await host.waitForTimeout(2500);
for (const p of peers) await p.keyboard.up("KeyW");
await host.waitForTimeout(800);
const end = await host.evaluate(() => [1, 2, 3].map((i) => { const t = grudge.world.heroForPlayer(i).transform.pos; return [t.x.toFixed(1), t.z.toFixed(1)]; }));
