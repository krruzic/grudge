import { chromium } from "playwright-core";
const BASE = "http://localhost:5199";
const ARGS = ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--no-sandbox", "--disable-background-timer-throttling", "--disable-renderer-backgrounding", "--disable-backgrounding-occluded-windows"];
const b = await chromium.launch({ executablePath: process.env.HOME + "/.cache/ms-playwright/chromium-1148/chrome-linux/chrome", args: ARGS });
const mk = async (name) => {
  const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
  const p = await ctx.newPage();
  p.on("pageerror", (e) => console.log(name, "PAGEERR", e.message));
  await p.goto(BASE + "/?screen=menu&page=network&debug", { waitUntil: "commit" });
  await p.waitForFunction(() => window.grudge && !document.getElementById("boot") && grudge.state === "menu", null, { timeout: 120000 });
  await p.waitForTimeout(500);
  return p;
};
const tap = async (p, k, ms = 120) => { await p.keyboard.down(k); await p.waitForTimeout(ms); await p.keyboard.up(k); await p.waitForTimeout(200); };
const toScreen = (p, id) => p.evaluate((id) => { const x = grudge.cursors.hits.find((k) => k.id === id); return x && { x: (x.x + x.w / 2) * innerWidth / (240 * innerWidth / innerHeight), y: (x.y + x.h / 2) * innerHeight / 240 }; }, id);
const click = async (p, id) => { const h = await toScreen(p, id); if (!h) { console.log("no hit", id); return; } await p.mouse.move(h.x, h.y, { steps: 6 }); await p.waitForTimeout(250); await p.mouse.down(); await p.waitForTimeout(80); await p.mouse.up(); await p.waitForTimeout(500); };
const host = await mk("host");
await tap(host, "Enter");
await host.waitForFunction(() => grudge.state === "select", null, { timeout: 15000 });
await host.evaluate(() => { const g = grudge; const i = g.slots.findIndex(() => true); });
await host.waitForTimeout(600);
const room = (await (await fetch(BASE + "/net/info")).json()).rooms.find((r) => r.phase === "lobby").id;
const peer = await mk("peer");
await tap(peer, "KeyD"); await tap(peer, "Enter");
console.log("host state", await host.evaluate(() => JSON.stringify([grudge.state, grudge.net])), JSON.stringify((await (await fetch(BASE + "/net/info")).json()).rooms));
await peer.waitForFunction(() => grudge.menus.page === "browse" && grudge.menus.rooms.length >= 1, null, { timeout: 15000 });
await peer.evaluate((id) => { grudge.menus.focus = grudge.menus.rooms.findIndex((r) => r.id === id) + 1; }, room);
await tap(peer, "Enter");
await peer.waitForFunction(() => grudge.state === "lobby", null, { timeout: 15000 });
await peer.mouse.move(640, 400, { steps: 4 }); await peer.waitForTimeout(1500);
console.log("peer seat", await peer.evaluate(() => JSON.stringify(grudge.net.mySlots)));
await peer.screenshot({ path: "/tmp/opencode/v/peer_css0.png" });
await click(host, "mode");
await host.waitForTimeout(800);
await peer.waitForTimeout(800);
await click(peer, "take:3");
await peer.waitForTimeout(1200);
console.log("after take", await peer.evaluate(() => JSON.stringify(grudge.net.mySlots)), await host.evaluate(() => JSON.stringify(grudge.slots.map((s) => [s.open ? "OPEN" : s.cpu ? "CPU" : "HUMAN", s.tag]))));
await click(peer, "hero:warden");
await peer.waitForTimeout(1000);
console.log("host sees", await host.evaluate(() => JSON.stringify(grudge.slots.map((s) => [s.hero, s.ready]))));
await peer.screenshot({ path: "/tmp/opencode/v/peer_css1.png" });
await host.evaluate(() => { const s = grudge.slots[0]; s.ready = true; grudge.cursors.placeChip(0, s.hero); grudge.cursors.cursors[0].holding = -1; });
await host.waitForTimeout(600);
await tap(host, "Enter"); await host.waitForTimeout(800); await tap(host, "Enter");
await peer.waitForFunction(() => grudge.state === "match", null, { timeout: 20000 });
console.log("match; peer controls slot", await peer.evaluate(() => JSON.stringify(grudge.net.mySlots)), "hero", await host.evaluate(() => grudge.world.heroForPlayer(3)?.hero.type));
await b.close();
